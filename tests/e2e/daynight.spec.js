import { test, expect } from '@playwright/test';
import { applyState } from '../../tools/lib/browser.js';

/**
 * @param {import('@playwright/test').Page} page
 * @param {string[]} names
 */
const worldState = (page, names) =>
  page.evaluate((props) => {
    const style = getComputedStyle(/** @type {Element} */ (document.querySelector('.polis')));
    return Object.fromEntries(props.map((p) => [p, Number(style.getPropertyValue(`--${p}`))]));
  }, names);

/**
 * Opacity of every wall's lit-window layer.
 * @param {import('@playwright/test').Page} page
 */
const windowLights = (page) =>
  page.$$eval('.bldg__wall--s', (walls) => walls.map((w) => Number(getComputedStyle(w, '::after').opacity)));

/**
 * The HUD clock as rendered. Its text is generated by CSS counters inside
 * ::before, so it is not in the DOM; Chromium's accessibility tree has it.
 * The decorative HUD is exposed for the test, then the clock's subtree is
 * read over CDP (both test browsers are Chromium-based).
 * @param {import('@playwright/test').Page} page
 */
async function hudClock(page) {
  await page.evaluate(() => document.querySelector('.hud')?.removeAttribute('aria-hidden'));
  const cdp = await page.context().newCDPSession(page);
  const { root } = await cdp.send('DOM.getDocument');
  const { nodeId } = await cdp.send('DOM.querySelector', { nodeId: root.nodeId, selector: '.hud__clock' });
  const { node } = await cdp.send('DOM.describeNode', { nodeId });
  const { nodes } = await cdp.send('Accessibility.getFullAXTree');
  const byId = new Map(nodes.map((n) => [n.nodeId, n]));
  const start = nodes.find((n) => n.backendDOMNodeId === node.backendNodeId);
  /** @type {string[]} */
  const text = [];
  const queue = [...(start?.childIds ?? [])];
  while (queue.length > 0) {
    const n = byId.get(/** @type {string} */ (queue.shift()));
    if (!n) continue;
    if (n.role?.value === 'StaticText') text.push(String(n.name?.value ?? ''));
    queue.push(...(n.childIds ?? []));
  }
  await cdp.detach();
  return text.join('');
}

test('auto mode runs the day, the sun, the clock and the minutes from .polis, opening at 15:00', async ({ page }) => {
  await page.goto('./');
  const names = await page.evaluate(() =>
    document
      .querySelector('.polis')
      ?.getAnimations()
      .map((a) => /** @type {CSSAnimation} */ (a).animationName)
      .sort(),
  );
  expect(names).toEqual(['polis-day', 'polis-hours', 'polis-minutes', 'polis-sun']);
  expect(await worldState(page, ['hour'])).toEqual({ hour: 15 });
  expect(await hudClock(page)).toBe('15:00');
});

test('the sun moves in one-second steps, so walls repaint once a second, not every frame', async ({ page }) => {
  await page.goto('./');
  const easing = await page.evaluate(() => {
    const sun = document
      .querySelector('.polis')
      ?.getAnimations()
      .find((a) => /** @type {CSSAnimation} */ (a).animationName === 'polis-sun');
    return sun?.effect instanceof KeyframeEffect ? sun.effect.getKeyframes()[0]?.easing : undefined;
  });
  expect(easing).toMatch(/^steps\(24(, end)?\)$/);
});

test('time advances one hour every four seconds in auto mode', async ({ page }) => {
  await page.goto('./');
  // Jump the three clock animations forward 9 s on the same timeline.
  await page.evaluate(() => {
    for (const a of document.querySelector('.polis')?.getAnimations() ?? []) {
      a.currentTime = Number(a.currentTime) + 9000;
    }
  });
  const { hour, minute } = await worldState(page, ['hour', 'minute']);
  expect(hour).toBe(17);
  expect(minute).toBe(15);
});

test('the night preset darkens the city, lights every window and shows 23:00', async ({ page }) => {
  await page.goto('./');
  await applyState(page, [['time', 'night']]);
  expect(await worldState(page, ['night', 'lights', 'sky-night', 'sky-day'])).toEqual({
    night: 1,
    lights: 1,
    'sky-night': 1,
    'sky-day': 0,
  });
  const lights = await windowLights(page);
  expect(Math.min(...lights)).toBe(1);
  expect(await hudClock(page)).toBe('23:00');
  const shade = await page.$eval('.block__shade', (el) => Number(getComputedStyle(el).opacity));
  expect(shade).toBe(0);
});

test('midday turns every window off and casts shadows', async ({ page }) => {
  await page.goto('./');
  await applyState(page, [['time', 'day']]);
  expect(Math.max(...(await windowLights(page)))).toBe(0);
  const shade = await page.$eval('.block__shade', (el) => Number(getComputedStyle(el).opacity));
  expect(shade).toBeGreaterThan(0.3);
  expect(await hudClock(page)).toBe('12:30');
});

test('at dawn the lights are half on: some buildings lit, others already dark', async ({ page }) => {
  await page.goto('./');
  await applyState(page, [['time', 'dawn']]);
  const lights = await windowLights(page);
  expect(lights.filter((o) => o === 1).length).toBeGreaterThan(5);
  expect(lights.filter((o) => o === 0).length).toBeGreaterThan(5);
});

test('changing the preset is a transition of the registered properties, not a jump', async ({ page }) => {
  await page.goto('./');
  await applyState(page, [['time', 'day']]);
  await page.check('input[name="time"][value="night"]', { force: true });
  const transitioning = await page.evaluate(() =>
    document
      .querySelector('.polis')
      ?.getAnimations()
      .filter((a) => a instanceof CSSTransition)
      .map((a) => /** @type {CSSTransition} */ (a).transitionProperty),
  );
  expect(transitioning).toEqual(expect.arrayContaining(['--night', '--lights', '--sky-night']));
});

test('shadows point away from the sun: west in the morning, east in the evening', async ({ page }) => {
  await page.goto('./');
  /** @param {string} time */
  const shear = async (time) => {
    await applyState(page, [['time', time]]);
    return page.$eval('.shade', (el) => new DOMMatrix(getComputedStyle(el).transform).c);
  };
  // matrix c = tan(skew): positive moves the north edge west.
  expect(await shear('dawn')).toBeGreaterThan(0);
  expect(await shear('dusk')).toBeLessThan(0);
});
